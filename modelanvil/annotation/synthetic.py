"""Synthetic record generation, provenance tracking, and evaluation leakage denial (WP-09 / TECH-014)."""
from __future__ import annotations

import hashlib
import time
from dataclasses import dataclass, field
from typing import Any, Callable, Optional

from django.core.exceptions import ValidationError
from django.utils import timezone

from modelanvil.runners.models import ModelVersion


@dataclass
class SyntheticRecord:
    record_id: str
    prompt: str
    output: str
    provenance: dict[str, Any]
    is_valid: bool = True
    validation_errors: list[str] = field(default_factory=list)


def generate_synthetic_records(
    *,
    prompt_template: str,
    prompt_revision: int,
    seed_inputs: list[dict[str, Any]],
    model_version: ModelVersion,
    generator_fn: Optional[Callable[[str, dict[str, Any]], str]] = None,
    decoding_params: Optional[dict[str, Any]] = None,
    protected_eval_hashes: Optional[set[str]] = None,
    cost_per_thousand_tokens: float = 0.002,
) -> list[SyntheticRecord]:
    """Generate synthetic examples with full provenance while denying protected eval cases (TECH-014).

    Guarantees:
    - Protected benchmark / evaluation cases are denied as seeds.
    - Generated records preserve prompt revision, model version, and decoding settings.
    - Output validation checks prevent corrupt or empty records from entering candidate pools.
    """
    params = decoding_params or {"temperature": 0.7, "max_tokens": 128}
    results: list[SyntheticRecord] = []
    protected = protected_eval_hashes or set()

    for idx, inp in enumerate(seed_inputs):
        text = str(inp.get("text") or inp.get("prompt") or "").strip()
        text_hash = hashlib.sha256(text.encode("utf-8")).hexdigest()

        # Check for leakage of protected evaluation cases (TECH-014)
        if text_hash in protected or any(p in text_hash for p in protected):
            raise ValidationError(
                f"Denied synthetic generation: seed input #{idx+1} matches a protected evaluation benchmark case."
            )

        full_prompt = prompt_template.replace("{input}", text) if "{input}" in prompt_template else f"{prompt_template}\n{text}"

        # Generate output
        if generator_fn:
            output = generator_fn(full_prompt, params)
        else:
            output = f"Synthetic response to '{text[:30]}' generated by {model_version.model.name}."

        # Compute token count estimate
        prompt_tokens = len(full_prompt.split())
        output_tokens = len(output.split())
        cost = ((prompt_tokens + output_tokens) / 1000.0) * cost_per_thousand_tokens

        provenance = {
            "origin": "synthetic",
            "model_version_id": str(model_version.model_version_id),
            "model_name": model_version.model.name,
            "prompt_revision": prompt_revision,
            "decoding_params": params,
            "token_count": prompt_tokens + output_tokens,
            "estimated_cost_dollars": round(cost, 6),
            "generated_at": timezone.now().isoformat(),
        }

        # Validation check
        is_valid = bool(output.strip())
        val_errors = [] if is_valid else ["Output is empty."]

        results.append(
            SyntheticRecord(
                record_id=f"syn-{idx+1}",
                prompt=full_prompt,
                output=output,
                provenance=provenance,
                is_valid=is_valid,
                validation_errors=val_errors,
            )
        )

    return results
